create table public.unidades_medida (
    id bigint generated by default as identity primary key,
    nombre text not null check (btrim(nombre) <> '')
);
create unique index unidades_medida_nombre_unico on public.unidades_medida (upper(btrim(nombre)));

create table public.marcas_repuestos (
    id bigint generated by default as identity primary key,
    nombre text not null check (btrim(nombre) <> '')
);
create unique index marcas_repuestos_nombre_unico on public.marcas_repuestos (upper(btrim(nombre)));

create table public.categorias_repuestos (
    id bigint generated by default as identity primary key,
    marca_id bigint not null references public.marcas_repuestos(id) on delete restrict,
    nombre text not null check (btrim(nombre) <> '')
);
create unique index categorias_repuestos_marca_nombre_unico
    on public.categorias_repuestos (marca_id, upper(btrim(nombre)));

create table public.marcas_vehiculos (
    id bigint generated by default as identity primary key,
    nombre text not null,
    fecha_creacion timestamptz not null default now()
);
create unique index marcas_vehiculos_nombre_unico on public.marcas_vehiculos (upper(btrim(nombre)));

create table public.modelos_vehiculos (
    id bigint generated by default as identity primary key,
    marca_id bigint not null references public.marcas_vehiculos(id) on delete restrict,
    nombre text not null,
    fecha_creacion timestamptz not null default now()
);
create unique index modelos_vehiculos_marca_nombre_unico
    on public.modelos_vehiculos (marca_id, upper(btrim(nombre)));

create table public.tipos_motor (
    id bigint generated by default as identity primary key,
    codigo text not null,
    descripcion text,
    fecha_creacion timestamptz not null default now()
);
create unique index tipos_motor_codigo_unico on public.tipos_motor (upper(btrim(codigo)));

create table public.repuestos (
    id bigint generated by default as identity primary key,
    codigo_sap text,
    codigo_proveedor text,
    descripcion text,
    medida text,
    descripcion_larga text,
    activo boolean not null default true,
    fecha_creacion timestamptz not null default now(),
    fecha_actualizacion timestamptz not null default now(),
    unidad_id bigint references public.unidades_medida(id) on delete restrict,
    marca_id bigint references public.marcas_repuestos(id) on delete restrict,
    categoria_id bigint references public.categorias_repuestos(id) on delete restrict,
    estado_gestion text not null default 'propuesto'
        check (estado_gestion in ('propuesto', 'en_cotizacion', 'pendiente_aprobacion',
                                  'aprobado', 'rechazado', 'pedido', 'en_sap')),
    minimo_compra numeric check (minimo_compra is null or minimo_compra > 0),
    precio_compra numeric check (precio_compra is null or precio_compra >= 0),
    precio_venta numeric check (precio_venta is null or precio_venta >= 0),
    cantidad_compra numeric check (cantidad_compra is null or cantidad_compra >= 0),
    constraint repuestos_sap_en_sap check
        (estado_gestion <> 'en_sap' or btrim(coalesce(codigo_sap, '')) <> '')
);
create unique index repuestos_codigo_sap_unico on public.repuestos (upper(btrim(codigo_sap)))
    where codigo_sap is not null and btrim(codigo_sap) <> '';
create unique index repuestos_codigo_proveedor_unico on public.repuestos (upper(btrim(codigo_proveedor)))
    where codigo_proveedor is not null and btrim(codigo_proveedor) <> '';
create index repuestos_descripcion_indice on public.repuestos (descripcion);
create index repuestos_estado_gestion on public.repuestos (estado_gestion);

create table public.codigos_oem (
    id bigint generated by default as identity primary key,
    repuesto_id bigint not null references public.repuestos(id) on delete cascade,
    codigo_oem text not null,
    fecha_creacion timestamptz not null default now()
);
create unique index codigos_oem_unico on public.codigos_oem (repuesto_id, upper(codigo_oem));

create table public.referencias_cruzadas (
    id bigint generated by default as identity primary key,
    repuesto_id bigint not null references public.repuestos(id) on delete cascade,
    tipo_referencia text not null,
    codigo_referencia text not null,
    fecha_creacion timestamptz not null default now()
);
create unique index referencias_cruzadas_unicas on public.referencias_cruzadas
    (repuesto_id, upper(tipo_referencia), upper(codigo_referencia));

create table public.aplicaciones_repuestos (
    id bigint generated by default as identity primary key,
    repuesto_id bigint not null references public.repuestos(id) on delete cascade,
    marca_id bigint not null references public.marcas_vehiculos(id) on delete restrict,
    modelo_id bigint not null references public.modelos_vehiculos(id) on delete restrict,
    tipo_motor_id bigint references public.tipos_motor(id) on delete restrict,
    cilindrada double precision check (cilindrada is null or cilindrada > 0),
    anio_desde integer check (anio_desde is null or anio_desde between 1886 and 2200),
    anio_hasta integer check (anio_hasta is null or anio_hasta between 1886 and 2200),
    texto_aplicacion text,
    fecha_creacion timestamptz not null default now(),
    check (anio_desde is null or anio_hasta is null or anio_desde <= anio_hasta)
);
create index aplicaciones_repuestos_busqueda_vehiculo
    on public.aplicaciones_repuestos (marca_id, modelo_id, anio_desde, anio_hasta);
create unique index aplicaciones_repuestos_unicas on public.aplicaciones_repuestos
    (repuesto_id, marca_id, modelo_id, coalesce(tipo_motor_id, 0), coalesce(cilindrada, 0),
     coalesce(anio_desde, 0), coalesce(anio_hasta, 0), upper(btrim(coalesce(texto_aplicacion, ''))));

create table public.lotes_importacion (
    id bigint generated by default as identity primary key,
    nombre_archivo text not null,
    nombre_hoja text,
    estado text not null default 'staged' check (estado in ('staged', 'confirmed', 'rejected')),
    total_filas integer not null default 0,
    filas_validas integer not null default 0,
    filas_error integer not null default 0,
    fecha_creacion timestamptz not null default now(),
    fecha_procesamiento timestamptz
);

create table public.filas_importacion (
    id bigint generated by default as identity primary key,
    lote_id bigint not null references public.lotes_importacion(id) on delete cascade,
    numero_fila integer not null,
    datos_originales text not null,
    datos_normalizados text,
    estado text not null check (estado in ('valid', 'error')),
    errores text,
    unique (lote_id, numero_fila)
);

create table public.historial_estados (
    id bigint generated by default as identity primary key,
    repuesto_id bigint not null references public.repuestos(id) on delete cascade,
    estado_anterior text,
    estado_nuevo text not null,
    fecha_cambio timestamptz not null default now()
);
create index historial_estados_repuesto on public.historial_estados (repuesto_id, id);

create view public.vista_repuestos with (security_invoker = true) as
select r.id, r.codigo_proveedor, r.codigo_sap, r.descripcion, r.medida,
       r.descripcion_larga, r.activo, r.fecha_creacion, r.fecha_actualizacion,
       r.unidad_id, r.marca_id, r.categoria_id, r.estado_gestion,
       r.minimo_compra, r.precio_compra, r.precio_venta, r.cantidad_compra,
       u.nombre as unidad, m.nombre as nombre_marca, c.nombre as categoria
from public.repuestos r
left join public.unidades_medida u on u.id = r.unidad_id
left join public.marcas_repuestos m on m.id = r.marca_id
left join public.categorias_repuestos c on c.id = r.categoria_id;
revoke all on public.vista_repuestos from anon, authenticated;

