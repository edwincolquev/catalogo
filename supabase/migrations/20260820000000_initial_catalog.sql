create extension if not exists pg_trgm;

create table public.parts (
    id bigint generated by default as identity primary key,
    sap_code text not null,
    supplier_code text,
    description text not null,
    measure text,
    brand_name text,
    long_description text,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create unique index parts_sap_code_unique on public.parts (upper(trim(sap_code)));
create index parts_description_trgm on public.parts using gin (description gin_trgm_ops);
create index parts_sap_code_trgm on public.parts using gin (sap_code gin_trgm_ops);

create table public.part_oem_codes (
    id bigint generated by default as identity primary key,
    part_id bigint not null references public.parts(id) on delete cascade,
    oem_code text not null,
    created_at timestamptz not null default now()
);

create unique index part_oem_codes_unique on public.part_oem_codes (part_id, upper(trim(oem_code)));
create index part_oem_codes_code_trgm on public.part_oem_codes using gin (oem_code gin_trgm_ops);

create table public.part_cross_references (
    id bigint generated by default as identity primary key,
    part_id bigint not null references public.parts(id) on delete cascade,
    reference_type text not null,
    reference_code text not null,
    created_at timestamptz not null default now()
);

create unique index part_cross_references_unique on public.part_cross_references (part_id, upper(trim(reference_type)), upper(trim(reference_code)));
create index part_cross_references_code_trgm on public.part_cross_references using gin (reference_code gin_trgm_ops);

create table public.vehicle_brands (
    id bigint generated by default as identity primary key,
    name text not null,
    created_at timestamptz not null default now()
);

create unique index vehicle_brands_name_unique on public.vehicle_brands (upper(trim(name)));

create table public.vehicle_models (
    id bigint generated by default as identity primary key,
    brand_id bigint not null references public.vehicle_brands(id) on delete restrict,
    name text not null,
    created_at timestamptz not null default now()
);

create unique index vehicle_models_brand_name_unique on public.vehicle_models (brand_id, upper(trim(name)));

create table public.engine_types (
    id bigint generated by default as identity primary key,
    code text not null,
    description text,
    created_at timestamptz not null default now()
);

create unique index engine_types_code_unique on public.engine_types (upper(trim(code)));

create table public.part_applications (
    id bigint generated by default as identity primary key,
    part_id bigint not null references public.parts(id) on delete cascade,
    brand_id bigint not null references public.vehicle_brands(id) on delete restrict,
    model_id bigint not null references public.vehicle_models(id) on delete restrict,
    engine_type_id bigint references public.engine_types(id) on delete restrict,
    displacement numeric(6,2),
    year_from smallint,
    year_to smallint,
    created_at timestamptz not null default now(),
    constraint part_applications_displacement_check check (displacement is null or displacement > 0),
    constraint part_applications_year_check check (year_from is null or year_to is null or year_from <= year_to)
);

create unique index part_applications_unique on public.part_applications (
    part_id,
    brand_id,
    model_id,
    coalesce(engine_type_id, 0),
    coalesce(displacement, 0),
    coalesce(year_from, 0),
    coalesce(year_to, 0)
);
create index part_applications_vehicle_lookup on public.part_applications (brand_id, model_id, year_from, year_to);

create or replace function public.generate_long_description(target_part_id bigint)
returns text
language sql
stable
as $$
    with part_data as (
        select p.description,
               nullif(trim(p.measure), '') as measure,
               (select string_agg(trim(o.oem_code), ', ' order by trim(o.oem_code))
                  from public.part_oem_codes o
                 where o.part_id = p.id) as oems
          from public.parts p
         where p.id = target_part_id
    ), applications_by_brand as (
        select a.brand_id,
               b.name as brand_name,
               string_agg(
                   concat_ws(' ',
                       upper(trim(vm.name)),
                       nullif(trim(et.description), ''),
                       case when a.displacement is not null then trim(to_char(a.displacement, 'FM999990.##')) end,
                       case
                           when a.year_from is not null and a.year_to is not null then 'DEL ' || right(a.year_from::text, 2) || ' AL ' || right(a.year_to::text, 2)
                           when a.year_from is not null then 'DESDE ' || a.year_from::text
                           when a.year_to is not null then 'HASTA ' || a.year_to::text
                       end
                   ),
                   '; ' order by vm.name, a.displacement, a.year_from, a.year_to
               ) as applications
          from public.part_applications a
          join public.vehicle_brands b on b.id = a.brand_id
          join public.vehicle_models vm on vm.id = a.model_id
          left join public.engine_types et on et.id = a.engine_type_id
         where a.part_id = target_part_id
         group by a.brand_id, b.name
    ), description_parts as (
        select array_remove(array[
            pd.description,
            pd.measure,
            case when pd.oems is not null then '(OEM: ' || pd.oems || ')' end,
            (select string_agg(upper(trim(ab.brand_name)) || ': ' || ab.applications, E'\n' order by upper(trim(ab.brand_name))) from applications_by_brand ab)
        ], null) as values
        from part_data pd
    )
    select array_to_string(values, E'\n')
      from description_parts;
$$;

create or replace function public.refresh_part_long_description()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    update public.parts
       set long_description = public.generate_long_description(coalesce(new.part_id, old.part_id)),
           updated_at = now()
     where id = coalesce(new.part_id, old.part_id);
    return coalesce(new, old);
end;
$$;

create or replace function public.set_part_long_description()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    new.long_description := public.generate_long_description(new.id);
    new.updated_at := now();
    return new;
end;
$$;

create or replace function public.refresh_part_row_long_description()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    update public.parts
       set long_description = public.generate_long_description(new.id),
           updated_at = now()
     where id = new.id;
    return new;
end;
$$;

create trigger parts_long_description_before_write
before insert or update of description, measure
on public.parts
for each row execute function public.set_part_long_description();

create trigger parts_long_description_after_write
after insert or update of description, measure
on public.parts
for each row execute function public.refresh_part_row_long_description();

create trigger oem_refresh_long_description
after insert or update or delete on public.part_oem_codes
for each row execute function public.refresh_part_long_description();

create trigger cross_reference_refresh_long_description
after insert or update or delete on public.part_cross_references
for each row execute function public.refresh_part_long_description();

create trigger application_refresh_long_description
after insert or update or delete on public.part_applications
for each row execute function public.refresh_part_long_description();

